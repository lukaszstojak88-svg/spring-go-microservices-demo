import org.springframework.data.domain.Page;
import org.springframework.data.domain.PageImpl;
import org.springframework.data.domain.PageRequest;
import org.springframework.data.domain.Pageable;
import org.springframework.data.domain.Sort;

/**
 * Service-layer unit tests. The repository is mocked; the real MapStruct-generated mapper is used
 * because it is a pure, dependency-free class. No Docker or Spring context required.
 */
@ExtendWith(MockitoExtension.class)
class ProductServiceTest {

  /** Nanoseconds on purpose: the service must truncate to milliseconds (MongoDB precision). */
  private static final Instant NOW = Instant.parse("2026-01-15T10:30:00.123456789Z");

  private static final Instant NOW_MILLIS = Instant.parse("2026-01-15T10:30:00.123Z");
  private static final Instant CREATED = Instant.parse("2026-01-01T08:00:00Z");

  @Mock private ProductRepository repository;

  private ProductService service;

  @BeforeEach
  void setUp() {
    Clock clock = Clock.fixed(NOW, ZoneOffset.UTC);
    service = new ProductService(repository, new ProductMapperImpl(), clock);
  }

  @Nested
  class Create {

    @Test
    void savesProductWithTimestampsAndReturnsResponse() {
      AtomicReference<String> idAtSaveTime = new AtomicReference<>("not-called");
      when(repository.save(any(Product.class)))
          .thenAnswer(
              inv -> {
                Product toSave = inv.getArgument(0);
                idAtSaveTime.set(toSave.getId());
                return withId(toSave, "p1");
              });

      ProductResponse response =
          service.create(
              new CreateProductRequest(
                  "Mechanical Keyboard", "Compact", new BigDecimal("349.99"), "PLN", true));

      assertThat(idAtSaveTime.get()).as("id is generated by MongoDB, not by the service").isNull();
      Product saved = captureSaved();
      assertThat(saved.getName()).isEqualTo("Mechanical Keyboard");
      assertThat(saved.getDescription()).isEqualTo("Compact");
      assertThat(saved.getPrice()).isEqualTo(new BigDecimal("349.99"));
      assertThat(saved.getCurrency()).isEqualTo("PLN");
      assertThat(saved.isAvailable()).isTrue();
      assertThat(saved.getCreatedAt()).isEqualTo(NOW_MILLIS);
      assertThat(saved.getUpdatedAt()).isEqualTo(NOW_MILLIS);

      assertThat(response.id()).isEqualTo("p1");
      assertThat(response.price()).isEqualTo("349.99");
      assertThat(response.createdAt()).isEqualTo(NOW_MILLIS);
    }

    @ParameterizedTest
    @CsvSource({
      "20, PLN, 20.00",
      "20.5, PLN, 20.50",
      "0, PLN, 0.00",
      "19.990, PLN, 19.99",
      "1500, JPY, 1500",
      "1500.00, JPY, 1500",
      "1.5, BHD, 1.500"
    })
    void normalizesPriceToCurrencyScale(String input, String currency, String expected) {
      when(repository.save(any(Product.class))).thenAnswer(inv -> withId(inv.getArgument(0), "p1"));

      ProductResponse response =
          service.create(
              new CreateProductRequest("Item", null, new BigDecimal(input), currency, true));

      assertThat(captureSaved().getPrice().toPlainString()).isEqualTo(expected);
      assertThat(response.price()).isEqualTo(expected);
    }

    @Test
    void neverRoundsSilently() {
      // Validation rejects this earlier; the service must fail loudly rather than round.
      assertThatThrownBy(
              () ->
                  service.create(
                      new CreateProductRequest("Item", null, new BigDecimal("1.999"), "PLN", true)))
          .isInstanceOf(ArithmeticException.class);
      verify(repository, never()).save(any());
    }
  }

  @Nested
  class Get {

    @Test
    void returnsExistingProduct() {
      when(repository.findById("p1")).thenReturn(Optional.of(stored("p1", "Mouse", "20.00")));

      ProductResponse response = service.get("p1");

      assertThat(response.id()).isEqualTo("p1");
      assertThat(response.name()).isEqualTo("Mouse");
      assertThat(response.price()).isEqualTo("20.00");
      assertThat(response.createdAt()).isEqualTo(CREATED);
    }

    @Test
    void throwsWhenProductIsMissing() {
      when(repository.findById("missing")).thenReturn(Optional.empty());

      assertThatThrownBy(() -> service.get("missing"))
          .isInstanceOf(ProductNotFoundException.class)
          .hasMessage("Product missing not found");
    }
  }

  @Nested
  class Update {

    @Test
    void replacesEditableFieldsKeepsCreatedAtAndRefreshesUpdatedAt() {
      when(repository.findById("p1")).thenReturn(Optional.of(stored("p1", "Mouse", "20.00")));
      when(repository.save(any(Product.class))).thenAnswer(inv -> inv.getArgument(0));

      ProductResponse response =
          service.update(
              "p1",
              new UpdateProductRequest(
                  "Mouse Pro", "Wireless", new BigDecimal("25.5"), "PLN", false));

      Product saved = captureSaved();
      assertThat(saved.getId()).isEqualTo("p1");
      assertThat(saved.getName()).isEqualTo("Mouse Pro");
      assertThat(saved.getDescription()).isEqualTo("Wireless");
      assertThat(saved.getPrice().toPlainString()).isEqualTo("25.50");
      assertThat(saved.isAvailable()).isFalse();
      assertThat(saved.getCreatedAt()).isEqualTo(CREATED);
      assertThat(saved.getUpdatedAt()).isEqualTo(NOW_MILLIS);
      assertThat(response.price()).isEqualTo("25.50");
    }

    @Test
    void clearsDescriptionWhenOmitted() {
      when(repository.findById("p1")).thenReturn(Optional.of(stored("p1", "Mouse", "20.00")));
      when(repository.save(any(Product.class))).thenAnswer(inv -> inv.getArgument(0));

      service.update(
          "p1", new UpdateProductRequest("Mouse", null, new BigDecimal("20"), "PLN", true));

      assertThat(captureSaved().getDescription()).isNull();
    }

    @Test
    void throwsWhenProductIsMissingAndSavesNothing() {
      when(repository.findById("missing")).thenReturn(Optional.empty());

      assertThatThrownBy(
              () ->
                  service.update(
                      "missing", new UpdateProductRequest("X", null, BigDecimal.ONE, "PLN", true)))
          .isInstanceOf(ProductNotFoundException.class);
      verify(repository, never()).save(any());
    }
  }

  @Nested
  class Delete {

    @Test
    void deletesExistingProduct() {
      when(repository.existsById("p1")).thenReturn(true);

      service.delete("p1");

      verify(repository).deleteById("p1");
    }

    @Test
    void throwsWhenProductIsMissingAndDeletesNothing() {
      when(repository.existsById("missing")).thenReturn(false);

      assertThatThrownBy(() -> service.delete("missing"))
          .isInstanceOf(ProductNotFoundException.class);
      verify(repository, never()).deleteById(anyString());
    }
  }

  @Nested
  class Lookup {

    @Test
    void returnsFoundProductsAndMissingIdsInRequestOrder() {
      when(repository.findAllById(List.of("b", "x", "a", "y")))
          .thenReturn(List.of(stored("a", "A", "1.00"), stored("b", "B", "2.00")));

      ProductBatchLookupResponse response = service.lookup(List.of("b", "x", "a", "y"));

      assertThat(response.products()).extracting(ProductResponse::id).containsExactly("b", "a");
      assertThat(response.missingIds()).containsExactly("x", "y");
    }

    @Test
    void ignoresDuplicateIds() {
      when(repository.findAllById(List.of("a", "x"))).thenReturn(List.of(stored("a", "A", "1.00")));

      ProductBatchLookupResponse response = service.lookup(List.of("a", "x", "a", "x"));

      assertThat(response.products()).extracting(ProductResponse::id).containsExactly("a");
      assertThat(response.missingIds()).containsExactly("x");
    }

    @Test
    void allMissingIsNotAnError() {
      when(repository.findAllById(List.of("x", "y"))).thenReturn(List.of());

      ProductBatchLookupResponse response = service.lookup(List.of("x", "y"));

      assertThat(response.products()).isEmpty();
      assertThat(response.missingIds()).containsExactly("x", "y");
    }
  }

  @Nested
  class ListProducts {

    @Test
    void mapsPageMetadataAndContent() {
      ArgumentCaptor<Pageable> pageable = ArgumentCaptor.forClass(Pageable.class);
      Page<Product> page =
          new PageImpl<>(
              List.of(stored("a", "A", "1.00"), stored("b", "B", "2.00")), PageRequest.of(1, 2), 5);
      when(repository.findAll(pageable.capture())).thenReturn(page);

      PaginatedResponse<ProductResponse> response = service.list(1, 2, "price,asc");

      assertThat(pageable.getValue().getPageNumber()).isEqualTo(1);
      assertThat(pageable.getValue().getPageSize()).isEqualTo(2);
      assertThat(pageable.getValue().getSort())
          .isEqualTo(Sort.by(Sort.Order.asc("price"), Sort.Order.asc("id")));
      assertThat(response.content()).extracting(ProductResponse::id).containsExactly("a", "b");
      assertThat(response.page()).isEqualTo(1);
      assertThat(response.size()).isEqualTo(2);
      assertThat(response.totalElements()).isEqualTo(5);
      assertThat(response.totalPages()).isEqualTo(3);
    }
  }

  @Nested
  class SortParsing {

    @Test
    void defaultsToNewestFirstWithIdTieBreaker() {
      Sort expected = Sort.by(Sort.Order.desc("createdAt"), Sort.Order.asc("id"));

      assertThat(ProductService.parseSort(null)).isEqualTo(expected);
      assertThat(ProductService.parseSort("  ")).isEqualTo(expected);
    }

    @ParameterizedTest
    @CsvSource({
      "'name', name, ASC",
      "'name,desc', name, DESC",
      "'price,ASC', price, ASC",
      "'updatedAt,desc', updatedAt, DESC",
      "' createdAt , asc ', createdAt, ASC"
    })
    void acceptsWhitelistedFields(String sort, String field, Sort.Direction direction) {
      assertThat(ProductService.parseSort(sort))
          .isEqualTo(Sort.by(new Sort.Order(direction, field), Sort.Order.asc("id")));
    }

    @ParameterizedTest
    @ValueSource(strings = {"id", "description", "foo,asc", "price,up", "price,asc,extra", ",asc"})
    void rejectsUnknownFieldsAndDirections(String sort) {
      assertThatThrownBy(() -> ProductService.parseSort(sort))
          .isInstanceOf(InvalidSortException.class);
    }
  }

  private Product captureSaved() {
    ArgumentCaptor<Product> captor = ArgumentCaptor.forClass(Product.class);
    verify(repository).save(captor.capture());
    return captor.getValue();
  }

  private static Product withId(Product product, String id) {
    product.setId(id);
    return product;
  }

  private static Product stored(String id, String name, String price) {
    Product product = new Product();
    product.setId(id);
    product.setName(name);
    product.setDescription("desc");
    product.setPrice(new BigDecimal(price));
    product.setCurrency("PLN");
    product.setAvailable(true);
    product.setCreatedAt(CREATED);
    product.setUpdatedAt(CREATED);
    return product;
  }
}
